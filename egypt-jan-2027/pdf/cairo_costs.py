# ── трансферы, ≈: автобус с водителем, USD за подачу/день, по размеру группы ──
# Заполняется по результату поиска по открытым источникам; None = «по запросу».
# ключ: вместимость автобуса; значения: (аэропорт→отель в одну сторону, полный день 8–10 ч, вечерний выезд туда-обратно)
TRANSFER = {
    'van12':    {'seats': 12, 'airport': 90,  'day': 200, 'evening': 100},
    'coaster25':{'seats': 25, 'airport': 150, 'day': 350, 'evening': 150},
    'coach48':  {'seats': 48, 'airport': 220, 'day': 550, 'evening': 250},
}
BAGGAGE_VAN = 60         # ≈ багажная машина на трансфер из аэропорта: от 20 чемоданов
NIGHT_SURCHARGE = 0.15   # ≈ резерв на ночную подачу после 00:00 («Ночь в музее»): нигде не документирована, но и не исключена

def buses(n):
    """Какими машинами везём группу n: одним автобусом на 48 либо микроавтобусами."""
    if n <= 12: return [('van12', 1)]
    if n <= 25: return [('coaster25', 1)]
    if n <= 48: return [('coach48', 1)]
    return [('coach48', math.ceil(n / 48))]

def tcost(n, kind):
    tot = 0
    for key, cnt in buses(n):
        v = TRANSFER[key][kind]
        if v is None: return None
        tot += v * cnt
    if kind == 'airport' and n >= 20:
        tot += BAGGAGE_VAN
    return tot

def fmt(x):
    if x is None: return '≈ по запросу'
    return '{:,.0f}'.format(x).replace(',', ' ')

def per(x, n):
    return None if x is None else x / n

def add(rows, name, group_fixed, per_head, mark='✓', note=''):
    rows.append((name, group_fixed, per_head, mark, note))

def block(title, rows, note_lines=()):
    out = ['', '## ' + title, '']
    hdr = '| Позиция | | На группу | На чел. | ' + ' | '.join('%d чел.' % g for g in GROUPS) + ' |'
    out.append(hdr); out.append('|' + '---|' * (4 + len(GROUPS)))
    tot = {g: 0.0 for g in GROUPS}; unknown = False
    for name, gf, ph, mark, note in rows:
        cells = []
        for g in GROUPS:
            if gf is None and ph is None:
                cells.append('≈ ?'); unknown = True
            else:
                v = (gf or 0) / g + (ph or 0)
                tot[g] += v; cells.append(fmt(v))
        out.append('| %s | %s | %s | %s | %s |' % (name + (' — ' + note if note else ''), mark,
                   fmt(gf) if gf is not None else '—', fmt(ph) if ph is not None else '—', ' | '.join(cells)))
    out.append('| **Итого на человека** | | | | ' + ' | '.join('**%s**%s' % (fmt(tot[g]), ' + ?' if unknown else '') for g in GROUPS) + ' |')
    out.extend(note_lines)
    return out

