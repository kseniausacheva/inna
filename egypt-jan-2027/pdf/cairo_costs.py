def transfer_block(title, items):
    out = ['', '## ' + title, '']
    out.append('| Переезд | | ' + ' | '.join('%d чел.: на группу / на чел.' % g for g in GROUPS) + ' |')
    out.append('|' + '---|' * (2 + len(GROUPS)))
    tot = {g: 0.0 for g in GROUPS}; unknown = False
    for label, kind, cnt in items:
        cells = []
        for g in GROUPS:
            c = tcost(g, kind)
            if c is None: cells.append('≈ по запросу'); unknown = True
            else:
                c *= cnt; tot[g] += c; cells.append('%s / %s' % (fmt(c), fmt(c / g)))
        out.append('| %s | ≈ | %s |' % (label, ' | '.join(cells)))
    out.append('| **Итого трансферы на человека** | | ' + ' | '.join(('**%s**' % fmt(tot[g] / g)) if not unknown else '≈ ?' for g in GROUPS) + ' |')
    return out

